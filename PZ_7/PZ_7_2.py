# Дана строка, состоящая из русских слов, разделенных пробелами (одним или несколькими).
# Вывести строку, содержащую эти же слова, разделенные одним символом «.» (точка).
# В конце строки точку не ставить.

string = input("Введите слова, разделенные пробелами: ")
strs = [x for x in string.strip().split(" ") if x != ""]

msg = ".".join(strs)
print(msg)