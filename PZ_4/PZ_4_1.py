# Вариант 21.
# 1. Дано вещественное число X (|X|<1) и целое число N (>0). Найти значение выражения
# X - (X^2)/2 + (X^3)/3 - ... + (-1)^(N -1) * (X^N)/N. Полученное число является приближенным
# значением функции ln в точке 1 + X.

import math

try:
    x = float(input("Введите X: "))
    n = int(input("Введите N: "))
except ValueError:
    print("Ошибка: введены некорректные данные! X должно быть дробным числом от -1 до 1, а N — целым.")
    exit(1)

if abs(x) >= 1:
    print("Ошибка: X должен быть в диапазоне (-1; 1)")
    exit(1)

result = 0.0
i = 1

while i <= n:
    term = ((-1) ** (i - 1)) * (x ** i) / i
    result += term
    i += 1

print("Результат выражения:", result)
print("Точное значение ln(1 + X):", math.log(1 + x))

